/**
 * Renders `docker-compose.override.oblihub.yml`, the per-stack resources override.
 *
 * Everything but `renderForTarget` is pure (no DB, no Docker) so a tsx script can exercise it;
 * engine facts, host snapshots and MPS detection are imported lazily inside `renderForTarget` for
 * the same reason.
 */

export const RESOURCES_OVERRIDE_FILE = 'docker-compose.override.oblihub.yml';
export const OBLIHUB_HEADER_PREFIX = '# Auto-generated by Oblihub';
export const VISIBLE_GPU_ID_RE = /^([0-9]{1,3}|GPU-[0-9a-fA-F-]{8,64})$/;

/** Service-level keys that compose-go requires to equal their deploy.resources twin. */
const SERVICE_LEVEL_RESOURCE_KEYS = ['cpus', 'mem_limit', 'pids_limit', 'mem_reservation'] as const;
export type ServiceLevelResourceKey = typeof SERVICE_LEVEL_RESOURCE_KEYS[number];

export interface ComposeServiceInfo {
  name: string;
  requestsGpu: boolean;
  gpuControllable: boolean;
  gpuUncontrollableReason: string | null;
  networkMode: string | null;
  ipc: string | null;
  /** Service-level resource keys as the merged files leave them (later file wins), verbatim: a
   *  string may still hold ${VAR} interpolation. Absent = none set. */
  serviceLevelResources?: Partial<Record<ServiceLevelResourceKey, string | number>>;
  /** The merged service declares a deploy.resources.limits block of its own. */
  hasDeployLimits?: boolean;
}

export interface RenderedOverride {
  yaml: string | null;
  warnings: string[];
  services: string[];
  cpus: string | null;
  memory: string | null;
  cpuShares: number | null;
  gpuMode: 'unchanged' | 'restricted' | 'revoked';
  mpsEmitted: boolean;
}

const NVIDIA_DEVICE_RE = /\/dev\/nvidia|nvidia\.com\/gpu/i;
const GPU_UUID_RE = /^GPU-[0-9a-fA-F-]{8,64}$/;
/** Verbs that create containers: only they may probe MPS liveness; others read the cache. */
const CREATING_VERBS = new Set(['up', 'create', 'run']);
const MPS_LIVE_WINDOW_MS = 60_000;
// Bounds how long a compose command waits for the MPS probe (a first probe may pull the helper
// image). The probe keeps running and fills the cache for the next command.
const MPS_PROBE_WAIT_MS = 30_000;
const SNAPSHOT_TIMEOUT_MS = 2_000;

export function defaultCpuShares(priority: StackPriority): number {
  switch (priority) {
    case 'critical': return 2048;
    case 'normal': return 1024;
    case 'opportunistic': return 128;
  }
}

export function formatMemoryBytes(bytes: number): string {
  // Compose accepts human-readable suffixes; prefer 'g' when the value is a clean GB, else 'm'.
  const mb = Math.floor(bytes / (1024 * 1024));
  if (mb % 1024 === 0 && mb >= 1024) return `${mb / 1024}g`;
  return `${mb}m`;
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return v != null && typeof v === 'object' && !Array.isArray(v);
}

function flattenStrings(v: unknown): string[] {
  if (typeof v === 'string') return [v];
  if (Array.isArray(v)) return v.flatMap(flattenStrings);
  return [];
}

function deviceRequestsGpu(dev: unknown): boolean {
  if (!isRecord(dev)) return false;
  if (dev.driver === 'nvidia') return true;
  // `capabilities` may be nested ([[gpu]]), as in the docker CLI's --gpus model.
  return flattenStrings(dev.capabilities).includes('gpu');
}

/** NVIDIA_VISIBLE_DEVICES set to something other than none/void/''. A bare list entry or a null map
 *  value passes the variable through from compose's environment: it counts as set. */
function envRequestsGpu(env: unknown): boolean {
  const grants = (value: string | null): boolean => value == null || !['none', 'void', ''].includes(value.trim().toLowerCase());
  if (Array.isArray(env)) {
    for (const entry of env) {
      if (typeof entry !== 'string') continue;
      const eq = entry.indexOf('=');
      const key = (eq < 0 ? entry : entry.slice(0, eq)).trim();
      if (key !== 'NVIDIA_VISIBLE_DEVICES') continue;
      if (grants(eq < 0 ? null : entry.slice(eq + 1))) return true;
    }
    return false;
  }
  if (isRecord(env) && Object.prototype.hasOwnProperty.call(env, 'NVIDIA_VISIBLE_DEVICES')) {
    const v = env.NVIDIA_VISIBLE_DEVICES;
    return grants(v == null ? null : String(v));
  }
  return false;
}

function mapsNvidiaDevice(devices: unknown): boolean {
  if (!Array.isArray(devices)) return false;
  return devices.some((d) => {
    if (typeof d === 'string') return NVIDIA_DEVICE_RE.test(d);
    if (isRecord(d)) {
      return [d.source, d.target].some((p) => typeof p === 'string' && NVIDIA_DEVICE_RE.test(p));
    }
    return false;
  });
}

interface ServiceAcc {
  requestsGpu: boolean;
  privileged: boolean;
  nvidiaDevices: boolean;
  gpusKey: boolean;
  networkMode: string | null;
  ipc: string | null;
  serviceLevel: Partial<Record<ServiceLevelResourceKey, string | number>>;
  deployLimits: boolean;
}

/** Whether this file declares deploy.resources.limits: undefined = it does not touch it (an earlier
 *  file's block stands), false = it removes it (null / `!reset`). */
function declaresDeployLimits(def: ComposeServiceDef): boolean | undefined {
  const has = (o: object, k: string) => Object.prototype.hasOwnProperty.call(o, k);
  if (!has(def, 'deploy')) return undefined;
  if (!isRecord(def.deploy)) return false;
  if (!has(def.deploy, 'resources')) return undefined;
  const resources = def.deploy.resources;
  if (!isRecord(resources)) return false;
  if (!has(resources, 'limits')) return undefined;
  return isRecord(resources.limits);
}

/**
 * Union of the services of every doc (base compose first, then the operator's own override), with
 * the GPU flags OR-ed over all docs. Services that are privileged, map /dev/nvidia* or
 * nvidia.com/gpu devices, or use the `gpus:` key see GPUs through a channel Oblihub cannot restrict,
 * so their GPU visibility is reported as not controllable. The service-level resource keys and the
 * presence of a deploy.resources.limits block are kept too: the renderer must not make them clash.
 */
export function inspectComposeServices(docs: Array<ComposeDoc | null>): ComposeServiceInfo[] {
  const order: string[] = [];
  const acc = new Map<string, ServiceAcc>();
  for (const doc of docs) {
    if (!doc || !isRecord(doc.services)) continue;
    for (const [name, rawDef] of Object.entries(doc.services)) {
      let a = acc.get(name);
      if (!a) {
        a = {
          requestsGpu: false, privileged: false, nvidiaDevices: false, gpusKey: false, networkMode: null, ipc: null,
          serviceLevel: {}, deployLimits: false,
        };
        acc.set(name, a);
        order.push(name);
      }
      if (!isRecord(rawDef)) continue;
      const def = rawDef as ComposeServiceDef;
      const reservations = isRecord(def.deploy) && isRecord(def.deploy.resources) && isRecord(def.deploy.resources.reservations)
        ? def.deploy.resources.reservations
        : null;
      const gpusKey = Object.prototype.hasOwnProperty.call(def, 'gpus');
      const nvidiaDevices = mapsNvidiaDevice(def.devices);
      if (def.runtime === 'nvidia'
        || (reservations != null && Array.isArray(reservations.devices) && reservations.devices.some(deviceRequestsGpu))
        || envRequestsGpu(def.environment)
        || gpusKey
        || nvidiaDevices) {
        a.requestsGpu = true;
      }
      if (def.privileged === true) a.privileged = true;
      if (nvidiaDevices) a.nvidiaDevices = true;
      if (gpusKey) a.gpusKey = true;
      // Later files override earlier ones, as compose merges them.
      if (typeof def.network_mode === 'string') a.networkMode = def.network_mode;
      if (typeof def.ipc === 'string') a.ipc = def.ipc;
      for (const key of SERVICE_LEVEL_RESOURCE_KEYS) {
        if (!Object.prototype.hasOwnProperty.call(def, key)) continue;
        const v = def[key];
        // The read schema keeps a tagged scalar raw: `!reset null` arrives as the string 'null'.
        if ((typeof v === 'string' && !/^(~|null|Null|NULL)?$/.test(v.trim())) || (typeof v === 'number' && Number.isFinite(v))) {
          a.serviceLevel[key] = v;
        } else {
          delete a.serviceLevel[key]; // null / `!reset` removes it
        }
      }
      const limitsDeclared = declaresDeployLimits(def);
      if (limitsDeclared !== undefined) a.deployLimits = limitsDeclared;
    }
  }
  return order.map((name) => {
    const a = acc.get(name)!;
    const reason = a.privileged ? 'privileged: true'
      : a.nvidiaDevices ? 'maps /dev/nvidia* or nvidia.com/gpu devices'
        : a.gpusKey ? 'uses the gpus: key'
          : null;
    return {
      name,
      requestsGpu: a.requestsGpu,
      gpuControllable: reason == null,
      gpuUncontrollableReason: reason,
      networkMode: a.networkMode,
      ipc: a.ipc,
      serviceLevelResources: { ...a.serviceLevel },
      hasDeployLimits: a.deployLimits,
    };
  });
}

function emptyRender(warnings: string[] = []): RenderedOverride {
  return { yaml: null, warnings, services: [], cpus: null, memory: null, cpuShares: null, gpuMode: 'unchanged', mpsEmitted: false };
}

/** A value copied from the operator's compose file. It is written unescaped so compose interpolates
 *  it here exactly as it does there; Oblihub's own strings are escaped. */
class Verbatim {
  constructor(public value: string | number) {}
}

function escapeDeep(value: unknown): unknown {
  if (value instanceof Verbatim) return value.value;
  if (typeof value === 'string') return escapeComposeDollars(value);
  if (value instanceof OverrideSeq) return new OverrideSeq(value.items.map(escapeDeep));
  if (Array.isArray(value)) return value.map(escapeDeep);
  if (isRecord(value)) {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value)) out[k] = escapeDeep(v);
    return out;
  }
  return value;
}

const round2 = (n: number) => Math.round(n * 100) / 100;

/** CUDA_MPS_PINNED_DEVICE_MEM_LIMIT value: whole GB as 'G'; a fractional GB in 'M', because the
 *  limit is parsed as an integer with a unit suffix. */
function formatPinnedLimit(gb: number): string {
  const rounded = Math.round(gb * 10) / 10;
  return Number.isInteger(rounded) ? `${rounded}G` : `${Math.round(rounded * 1024)}M`;
}

interface MpsPlan {
  dir: string;
  env: Record<string, string>;
}

/**
 * The MPS client settings for the GPU services, or null when nothing MPS-related may be emitted.
 * Without a daemon that answered in that exact directory within the last 60 s, the clients
 * would either fail to connect or silently run uncapped, so nothing is emitted and a warning says so.
 */
function mpsPlanFor(
  mps: MpsSettings,
  visibleGpuIds: string[] | null,
  validGpuIds: string[] | null,
  gpuUuidByIndex: Record<string, string> | null | undefined,
  mpsLive: boolean | undefined,
  warnings: string[],
): MpsPlan | null {
  const dir = normalizeMpsPipeDir(mps.pipeDirectory ?? DEFAULT_MPS_PIPE_DIR);
  if (dir == null) {
    warnings.push(`MPS pipe directory "${String(mps.pipeDirectory).slice(0, 64)}" is not one of /tmp/nvidia-mps, /run/nvidia-mps, /var/run/nvidia-mps — MPS settings not applied`);
    return null;
  }
  if (mpsLive !== true) {
    warnings.push(`MPS is enabled but no live MPS daemon was seen in ${dir} within the last 60 s — MPS settings not applied (the miner runs as a plain CUDA process)`);
    return null;
  }
  if (validGpuIds != null && validGpuIds.length === 0) {
    warnings.push('MPS settings not applied: GPU visibility is set to no GPU');
    return null;
  }

  const env: Record<string, string> = { CUDA_MPS_PIPE_DIRECTORY: dir };
  const pct = mps.activeThreadPercentage;
  if (pct != null) {
    if (typeof pct === 'number' && Number.isInteger(pct) && pct >= 1 && pct <= 100) env.CUDA_MPS_ACTIVE_THREAD_PERCENTAGE = String(pct);
    else warnings.push(`MPS SM percentage "${String(pct).slice(0, 16)}" is not an integer between 1 and 100 — not applied`);
  }

  const pinned: string[] = [];
  for (const [uuid, gb] of Object.entries(mps.pinnedMemLimitGb ?? {})) {
    if (GPU_UUID_RE.test(uuid) && typeof gb === 'number' && Number.isFinite(gb) && gb > 0) pinned.push(`${uuid}=${formatPinnedLimit(gb)}`);
    else warnings.push(`MPS VRAM cap for "${uuid.slice(0, 72)}" is invalid — not applied`);
  }
  if (pinned.length > 0) env.CUDA_MPS_PINNED_DEVICE_MEM_LIMIT = pinned.join(',');

  // MPS clients enumerate the GPUs of the daemon's scope, not only the container's device nodes, so
  // the restriction is repeated for CUDA. By UUID: indices are renumbered inside the container.
  if (visibleGpuIds != null && validGpuIds != null) {
    const uuids: string[] = [];
    const missing: string[] = [];
    for (const id of validGpuIds) {
      const uuid = GPU_UUID_RE.test(id) ? id : gpuUuidByIndex?.[id];
      if (uuid != null && GPU_UUID_RE.test(uuid)) uuids.push(uuid);
      else missing.push(id);
    }
    if (missing.length > 0) {
      warnings.push(`CUDA_VISIBLE_DEVICES not set for the MPS clients: no UUID known for GPU ${missing.join(', ')} — they may see every GPU of the MPS daemon`);
    } else if (uuids.length > 0) {
      env.CUDA_VISIBLE_DEVICES = uuids.join(',');
    }
  }
  return { dir, env };
}

export function renderResourcesOverride(input: {
  projectName: string;
  limits: ResourceLimits | null;
  services: ComposeServiceInfo[];
  capacity: { cpuCount: number | null; memTotalBytes: number | null };
  /** GPU index → uuid on the stack's engine; used to give MPS clients CUDA_VISIBLE_DEVICES by uuid. */
  gpuUuidByIndex?: Record<string, string> | null;
  /** A live MPS daemon answered in the stack's pipe directory within the last 60 s. */
  mpsLive?: boolean;
}): RenderedOverride {
  const { projectName, limits, services, capacity } = input;
  if (limits == null || services.length === 0) return emptyRender();

  const warnings: string[] = [];
  const cpuShares = limits.cpuShares ?? defaultCpuShares(limits.priority);

  let cpus: string | null = null;
  const cpuPercent = limits.cpuPercent ?? 0;
  if (cpuPercent > 0) {
    if (capacity.cpuCount) cpus = String(Math.max(0.01, round2((cpuPercent / 100) * capacity.cpuCount)));
    else warnings.push("CPU cap skipped: the capacity of this stack's engine is unknown");
  }

  let memory: string | null = null;
  const ramPercent = limits.ramPercent ?? 0;
  if (ramPercent > 0) {
    if (capacity.memTotalBytes) memory = formatMemoryBytes(Math.max(6 * 1024 * 1024, Math.floor((ramPercent / 100) * capacity.memTotalBytes)));
    else warnings.push("RAM cap skipped: the capacity of this stack's engine is unknown");
  }

  // GPU visibility. null = emit nothing GPU-related: the old renderer injected `runtime: nvidia` +
  // `NVIDIA_VISIBLE_DEVICES=all` into every capped service, which granted GPUs to services that never
  // asked for one and broke `up` on GPU-less engines. `runtime` is never emitted.
  const ids = limits.visibleGpuIds;
  let gpuIds: string[] | null = null;
  if (ids != null) {
    const invalid = ids.filter((id) => typeof id !== 'string' || !VISIBLE_GPU_ID_RE.test(id));
    if (invalid.length > 0) {
      warnings.push(`GPU visibility skipped: invalid GPU id(s) ${invalid.map((id) => String(id).slice(0, 40)).join(', ')}`);
    } else {
      gpuIds = [...ids];
      if (!services.some((s) => s.requestsGpu)) {
        warnings.push('No service requests a GPU in its compose file — GPU visibility has no effect');
      }
    }
  }

  const mpsPlan = limits.mps?.enabled
    ? mpsPlanFor(limits.mps, ids ?? null, gpuIds, input.gpuUuidByIndex, input.mpsLive, warnings)
    : null;
  const mpsClients: string[] = [];

  let gpuApplied = false;
  const out: Record<string, unknown> = {};
  for (const svc of services) {
    const block: Record<string, unknown> = { cpu_shares: cpuShares };
    const resources: Record<string, unknown> = {};
    const svcLevel = svc.serviceLevelResources ?? {};
    if (cpus != null || memory != null) {
      // compose-go refuses a service whose service-level cpus / mem_limit / pids_limit differs from
      // its deploy.resources.limits twin once a limits block exists, a missing twin counting as 0.
      // This file rides on every verb (down and stop included), so a base `mem_limit: 8g` next to
      // our limits block, even one holding only cpus, would block the whole stack. A service with
      // such keys and no limits block of its own gets the caps as service-level keys (a later -f
      // file's scalar replaces the base's) and no limits block; one with both gets them on both.
      const serviceLevelOnly = svc.hasDeployLimits !== true
        && (svcLevel.cpus != null || svcLevel.mem_limit != null || svcLevel.pids_limit != null);
      const limitsOut: Record<string, unknown> = {};
      for (const cap of [
        { key: 'cpus', field: 'cpus', value: cpus, label: 'CPU cap' },
        { key: 'mem_limit', field: 'memory', value: memory, label: 'RAM cap' },
      ] as const) {
        if (cap.value == null) continue;
        if (svcLevel[cap.key] != null || serviceLevelOnly) {
          // A number: compose then decodes it float64 → float32 exactly as it decodes deploy's
          // string, so the two compare equal.
          block[cap.key] = cap.key === 'cpus' ? Number(cap.value) : cap.value;
        }
        if (svcLevel[cap.key] != null) {
          warnings.push(`Service "${svc.name}": ${cap.key} from its compose file is replaced by Oblihub's ${cap.label} (${cap.value})`);
        }
        if (!serviceLevelOnly) limitsOut[cap.field] = cap.value;
      }
      if (Object.keys(limitsOut).length > 0) resources.limits = limitsOut;
    }
    if (gpuIds != null && svc.requestsGpu) {
      if (!svc.gpuControllable) {
        warnings.push(`GPU visibility not applied to service "${svc.name}": ${svc.gpuUncontrollableReason ?? 'not controllable'}`);
      } else {
        // GPU visibility travels on TWO channels because nvidia-container-toolkit resolves them
        // differently depending on how the base compose declares GPUs:
        //  - `NVIDIA_VISIBLE_DEVICES` env — the LEGACY channel, honored by nvidia-container-runtime
        //    when the container is launched without a CDI/`--gpus` request (base uses only
        //    `runtime: nvidia` + this env).
        //  - `deploy.resources.reservations.devices[].device_ids` — the device-request/CDI channel. If
        //    the base declares any `devices` block (even `count: all`), the runtime IGNORES
        //    NVIDIA_VISIBLE_DEVICES and only the device request matters — the classic "I set
        //    NVIDIA_VISIBLE_DEVICES=0, why do I still see both GPUs" bug.
        // Both are emitted so the restriction holds whichever style the base uses; `!override`
        // makes our device list replace the base's instead of being appended to it.
        block.environment = { NVIDIA_VISIBLE_DEVICES: gpuIds.length === 0 ? 'none' : gpuIds.join(',') };
        resources.reservations = {
          devices: new OverrideSeq(gpuIds.length === 0
            ? []
            : [{ driver: 'nvidia', device_ids: [...gpuIds], capabilities: ['gpu'] }]),
          // Same compose-go rule for mem_reservation once a reservations block exists; an existing
          // reservations.memory already equals it (compose refuses the base otherwise).
          ...(svcLevel.mem_reservation != null ? { memory: new Verbatim(svcLevel.mem_reservation) } : {}),
        };
        gpuApplied = true;
      }
    }
    // MPS clients = the services whose GPU access Oblihub controls. The runtime / device request
    // logic above stays as it is: the toolkit must still inject libcuda.
    if (mpsPlan && svc.requestsGpu) {
      if (!svc.gpuControllable) {
        warnings.push(`MPS not applied to service "${svc.name}": ${svc.gpuUncontrollableReason ?? 'GPU access not controllable'}`);
      } else {
        block.environment = { ...(block.environment as Record<string, string> | undefined), ...mpsPlan.env };
        // The MPS server and its clients share memory through the IPC namespace.
        if (svc.ipc != null && svc.ipc !== 'host') {
          warnings.push(`Service "${svc.name}": ipc "${svc.ipc}" from its compose file is replaced by ipc: host (required by MPS clients)`);
        }
        block.ipc = 'host';
        // Long syntax with create_host_path false: compose then fails on a missing directory instead
        // of creating an empty one, which would silently disconnect the clients from the daemon.
        block.volumes = [{ type: 'bind', source: mpsPlan.dir, target: mpsPlan.dir, bind: { create_host_path: false } }];
        mpsClients.push(svc.name);
      }
    }
    if (Object.keys(resources).length > 0) block.deploy = { resources };
    out[svc.name] = block;
  }
  if (mpsPlan && mpsClients.length === 0) {
    warnings.push('MPS is enabled but no service requests a GPU Oblihub can control — nothing MPS-related was emitted');
  }

  const header = [
    "# Auto-generated by Oblihub from the stack's Resources tab — DO NOT EDIT",
    "# Re-rendered from Oblihub's database before every compose command (hand edits are lost).",
    `# Running compose by hand? Include it: docker compose -p ${projectName.replace(/[\r\n]/g, '')} -f <compose file> [-f docker-compose.override.yml] -f ${RESOURCES_OVERRIDE_FILE} ...`,
    '',
  ].join('\n');

  return {
    yaml: header + dumpComposeYaml(escapeDeep({ services: out })),
    warnings,
    services: services.map((s) => s.name),
    cpus,
    memory,
    cpuShares,
    gpuMode: gpuApplied && gpuIds != null ? (gpuIds.length === 0 ? 'revoked' : 'restricted') : 'unchanged',
    mpsEmitted: mpsClients.length > 0,
  };
}

/**
 * MPS inputs of the render: daemon liveness in the stack's pipe directory and the engine's GPU
 * uuids. Only creating verbs may probe (a helper container on the engine); every other verb and
 * the read-only preview use the cache.
 */
async function mpsInputsFor(mps: MpsSettings, engineId: number, visibleGpuIds: string[] | null, verb: string | undefined): Promise<{
  mpsLive: boolean;
  gpuUuidByIndex: Record<string, string> | null;
  warnings: string[];
}> {
  const warnings: string[] = [];
  const dir = mps.pipeDirectory ?? DEFAULT_MPS_PIPE_DIR;
  const { mpsDetectionService, MPS_PLAIN_UNKNOWN_MESSAGES } = await import('./mpsDetection.service');
  let mpsLive: boolean;
  if (verb !== undefined && CREATING_VERBS.has(verb)) {
    // These warnings reach every consumer (stream lead lines in the stack's compose room, the apply
    // result, the preview): an 'unknown' status other than the fixed lines, and a check that threw,
    // quote raw Docker/ssh text that can name the engine's address. Their text goes to the server
    // log only. The two replacement lines are the exact ones resourceLimits.previewWarningsForViewer
    // passes through as already redacted.
    try {
      const st = await withTimeout(mpsDetectionService.getStatus(engineId, dir, { maxAgeMs: MPS_LIVE_WINDOW_MS }), MPS_PROBE_WAIT_MS, 'MPS daemon check');
      const checkedAt = st.checkedAt != null ? Date.parse(st.checkedAt) : NaN;
      mpsLive = st.daemon === 'detected' && Number.isFinite(checkedAt) && Date.now() - checkedAt <= MPS_LIVE_WINDOW_MS;
      if (!mpsLive && st.message) {
        if (st.daemon === 'unknown' && !MPS_PLAIN_UNKNOWN_MESSAGES.has(st.message)) {
          logger.warn({ engineId, dir, message: st.message }, 'MPS daemon check failed');
          warnings.push('MPS daemon check: MPS daemon check unavailable (details in the server log)');
        } else {
          warnings.push(`MPS daemon check: ${st.message}`);
        }
      }
    } catch (err) {
      mpsLive = false;
      logger.warn({ engineId, dir, err: err instanceof Error ? err.message : String(err) }, 'MPS daemon check did not finish');
      warnings.push('MPS daemon check did not finish (details in the server log)');
    }
  } else {
    mpsLive = mpsDetectionService.isLive(engineId, dir, MPS_LIVE_WINDOW_MS);
  }

  // Only needed to turn visible GPU indices into uuids for CUDA_VISIBLE_DEVICES.
  let gpuUuidByIndex: Record<string, string> | null = null;
  if (mpsLive && visibleGpuIds?.some((id) => !GPU_UUID_RE.test(id))) {
    const map: Record<string, string> = {};
    try {
      const { engineHostService } = await import('./engineHost.service');
      const snap = await withTimeout(engineHostService.getSnapshot(engineId), SNAPSHOT_TIMEOUT_MS, 'host snapshot');
      for (const g of snap?.gpu.gpus ?? []) if (g.uuid) map[g.index] = g.uuid;
    } catch {
      // Fall back to the GPU list the last probe saw (at most 60 s old when the daemon is live).
    }
    if (Object.keys(map).length === 0) {
      for (const g of mpsDetectionService.peek(engineId, dir)?.gpus ?? []) if (g.uuid) map[g.index] = g.uuid;
    }
    gpuUuidByIndex = map;
  }
  return { mpsLive, gpuUuidByIndex, warnings };
}

/**
 * Parse the compose texts of a target, look up its engine's capacity and render. MPS liveness is
 * probed here for creating verbs only.
 */
export async function renderForTarget(input: {
  projectName: string;
  limits: ResourceLimits | null;
  /** [base compose, operator's own override]; null = file absent. */
  composeTexts: Array<string | null>;
  engineId: number | null;
  daemonKey: string;
  /** Compose verb about to run; undefined = read-only preview (cache-only capacity). */
  verb?: string;
}): Promise<RenderedOverride> {
  const { projectName, limits, composeTexts, engineId, daemonKey, verb } = input;
  if (limits == null) return emptyRender();

  const warnings: string[] = [];
  const docs: Array<ComposeDoc | null> = [];
  for (let i = 0; i < composeTexts.length; i++) {
    const text = composeTexts[i];
    if (text == null) { docs.push(null); continue; }
    const { doc, error } = parseComposeYaml(text);
    if (error != null) {
      if (i === 0) return emptyRender([`Compose file could not be parsed (${error}) — resource override not rendered`]);
      warnings.push(`Override file could not be parsed (${error}) — its services were not inspected`);
    }
    docs.push(doc);
  }
  const services = inspectComposeServices(docs);

  let cpuCount: number | null = null;
  let memTotalBytes: number | null = null;
  const wantsCpu = (limits.cpuPercent ?? 0) > 0;
  const wantsRam = (limits.ramPercent ?? 0) > 0;
  if (engineId != null && (wantsCpu || wantsRam)) {
    const { engineFactsService } = await import('./engineFacts.service');
    // A read-only preview (the generated-files GET) only reads the cache and never blocks: a cold
    // cache for a remote engine used to make that GET wait up to 8 s on remote Docker. A real
    // command writes the file it then runs with, so it waits (bounded) for real numbers.
    const facts = verb === undefined
      ? engineFactsService.peek(engineId)
      : await engineFactsService.get(engineId, { timeoutMs: 8_000 });
    cpuCount = facts?.cpuCount ?? null;
    memTotalBytes = facts?.memTotalBytes ?? null;
  }
  // The local daemon is this host; a remote engine's unknown capacity stays unknown and its
  // caps are skipped with a warning — never sized from the hub's numbers.
  if (daemonKey === 'local') {
    if (cpuCount == null) cpuCount = os.cpus().length || null;
    if (memTotalBytes == null) memTotalBytes = os.totalmem() || null;
  }
  if (verb === undefined && daemonKey !== 'local'
    && ((wantsCpu && cpuCount == null) || (wantsRam && memTotalBytes == null))) {
    warnings.push('Engine capacity not cached yet — this preview may omit the CPU/RAM caps (the next compose command renders them)');
  }

  let mpsLive = false;
  let gpuUuidByIndex: Record<string, string> | null = null;
  // An orphaned stack (no engine) is never live: nothing MPS-related is emitted.
  if (limits.mps?.enabled && engineId != null) {
    const mpsInputs = await mpsInputsFor(limits.mps, engineId, limits.visibleGpuIds, verb);
    mpsLive = mpsInputs.mpsLive;
    gpuUuidByIndex = mpsInputs.gpuUuidByIndex;
    warnings.push(...mpsInputs.warnings);
  }

  const rendered = renderResourcesOverride({
    projectName, limits, services, capacity: { cpuCount, memTotalBytes }, gpuUuidByIndex, mpsLive,
  });
  return { ...rendered, warnings: [...warnings, ...rendered.warnings] };
}
